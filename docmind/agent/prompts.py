"""
Agent 各节点的提示词（Phase 2）

【为什么把提示词单独放在一个文件里】

新手写 Agent 最常见的做法是把提示词硬编码在各个函数里，结果：
    1. 想改一句话要翻遍代码
    2. 做消融实验时无法只改提示词而不动逻辑
    3. 提示词版本迭代没有记录

单独成文件后，Phase 3 的消融实验可以做到"提示词 A/B 对照"，
这在面试时是很能讲的一件事：说明你不是拍脑袋写提示词，而是有对照的。

【所有提示词的共同设计原则】

1. **强制结构化输出**。让模型输出 JSON，而不是自由文本。
   自由文本要靠正则去"猜"模型想表达什么，非常脆弱 ——
   模型换个说法你的解析就挂了。
   代价是 JSON 有时不合法，所以下面每个提示词都配了兜底解析
   （见 state.py 里的 _parse_json 容错逻辑）。

2. **明确给出"不做什么"**。光说"请检索相关文档"没用，
   要说"不要使用你自己的知识，只能使用给定证据"。
   7B 模型的指令遵循能力有限，约束必须写得非常直白。

3. **给输出示例**。Few-shot 对 7B 级别的模型效果提升非常明显。
"""


def evidence_label(index: int) -> str:
    """Alphabetic citation handles cannot be confused with PDF reference numbers."""
    if index < 1:
        raise ValueError('Evidence labels start at one')
    label = ''
    while index:
        index, digit = divmod(index-1,26)
        label = chr(65+digit)+label
    return 'EVID_'+label


def normalize_evidence_citations(answer: str) -> str:
    import re
    def replace(match):
        value = 0
        for char in match.group(1).upper():
            value = value*26+ord(char)-64
        return f'[{value}]'
    return re.sub(r'\[EVID_([A-Z]+)\]',replace,answer,flags=re.IGNORECASE)


def format_evidence(chunks: list[tuple[int, str, str]], max_chars: int | None = None,
                    opaque_labels: bool = False) -> str:
    """把检索到的 chunk 格式化成给模型看的证据块。

    参数
    ----
    chunks : [(编号, 文本, 来源文件名), ...]，编号从 1 开始

    为什么要有编号？
    因为引用溯源是 RAG 系统的核心价值 —— 用户要能点开看"这句话是从哪篇
    论文第几段来的"。没有编号，模型就只能说"根据文档"，这在学术场景是
    不可接受的。

    上下文长度如何控制？
    默认传递完整正文，避免数学结论位于尾部时被无提示截掉。
    如调用方明确设置 max_chars，则截断位置带标记；留痕时必须区分
    语料全文和实际模型上下文。上下文大小由调用方选择证据数控制。
    """
    parts = []
    for idx, text, source in chunks:
        snippet = text if max_chars is None or len(text) <= max_chars else text[:max_chars] + " …[截断]"
        label = evidence_label(idx) if opaque_labels else str(idx)
        parts.append(f"[{label}] 来源: {source}\n{snippet}")
    return "\n\n".join(parts)
